export function getWorkoutTemplate(id: string): WorkoutTemplate | null {
  return WORKOUT_TEMPLATES.find((template) => template.id === id) ?? null
}

export function getTemplateForWeekday(weekday: number): WorkoutTemplate | null {
  return getWorkoutTemplate(DEFAULT_WEEK_SCHEDULE[weekday] ?? "")
}

export function createWorkoutExercise(
  template: ExerciseTemplate,
): WorkoutExercise {
  return {
    ...template,
    actualReps: Array.from({ length: template.targetSets }, () => 0),
    statusOverride: null,
  }
}

export function createWorkoutFromTemplate(
  template: WorkoutTemplate,
  date: string,
): WorkoutRecord {
  return {
    date,
    templateId: template.id,
    name: template.name,
    category: template.category,
    focus: template.focus,
    description: template.description,
    exercises: template.exercises.map(createWorkoutExercise),
    updatedAt: new Date().toISOString(),
  }
}

