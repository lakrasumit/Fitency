function fromLibrary(
  id: string,
  overrides: Partial<Pick<ExerciseTemplate, "targetSets" | "targetReps">> = {},
): ExerciseTemplate {
  const exerciseTemplate = EXERCISE_LIBRARY[id]
  if (!exerciseTemplate) throw new Error(`Unknown exercise: ${id}`)
  return { ...exerciseTemplate, ...overrides }
}

